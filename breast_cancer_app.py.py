from sklearn.preprocessing import StandardScaler
from sklearn.cluster import KMeans
from sklearn.decomposition import PCA
import matplotlib.pyplot as plt
import seaborn as sns

# 1. Prepare and scale features (excluding the target 'classification')
features_cols = [col for col in data.columns if col != 'classification']
scaler = StandardScaler()
scaled_features = scaler.fit_transform(data[features_cols])

# 2. Reduce dimensions to 2D for scatter plotting using PCA
pca = PCA(n_components=2)
pca_features = pca.fit_transform(scaled_features)

# 3. Setup a grid of scatter plots for K = 2, 3, 4, 5
fig, axes = plt.subplots(2, 2, figsize=(16, 12))
axes = axes.ravel()

for idx, k in enumerate([2, 3, 4, 5]):
    kmeans = KMeans(n_clusters=k, random_state=42, n_init=10)
    labels = kmeans.fit_predict(scaled_features)

    # Scatter plot on PCA component space
    sns.scatterplot(
        x=pca_features[:, 0],
        y=pca_features[:, 1],
        hue=labels,
        palette='Set1',
        ax=axes[idx],
        legend='full',
        alpha=0.8
    )
    axes[idx].set_title(f'PCA Scatter Plot: K = {k} Clusters', fontsize=14)
    axes[idx].set_xlabel('Principal Component 1', fontsize=11)
    axes[idx].set_ylabel('Principal Component 2', fontsize=11)
    axes[idx].legend(title='Cluster')

plt.suptitle('K-Means Clustering Scatter Plots (K = 2, 3, 4, 5)', fontsize=18, y=0.98)
plt.tight_layout()
plt.show()

from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestClassifier
from sklearn.neighbors import KNeighborsClassifier
from sklearn.metrics import confusion_matrix, ConfusionMatrixDisplay
import matplotlib.pyplot as plt

# 1. Use K-Means with K=3 to generate cluster target labels
kmeans = KMeans(n_clusters=3, random_state=42, n_init=10)
cluster_targets = kmeans.fit_predict(scaled_features)

# 2. Split data into train and test sets (70% train, 30% test)
X_train, X_test, y_train, y_test = train_test_split(
    scaled_features, cluster_targets, test_size=0.3, random_state=42, stratify=cluster_targets
)

# 3. Train Random Forest Classifier
rf_model = RandomForestClassifier(random_state=42)
rf_model.fit(X_train, y_train)
y_pred_rf = rf_model.predict(X_test)

# 4. Train K-Nearest Neighbors Classifier
knn_model = KNeighborsClassifier(n_neighbors=5)
knn_model.fit(X_train, y_train)
y_pred_knn = knn_model.predict(X_test)

# 5. Visualize Confusion Matrices side-by-side
fig, axes = plt.subplots(1, 2, figsize=(14, 5))

# Random Forest Confusion Matrix
cm_rf = confusion_matrix(y_test, y_pred_rf)
cmd_rf = ConfusionMatrixDisplay(confusion_matrix=cm_rf, display_labels=[f'Cluster {i}' for i in range(3)])
cmd_rf.plot(ax=axes[0], cmap='Blues', values_format='d')
axes[0].set_title('Random Forest Confusion Matrix (Predicting Clusters)')
axes[0].grid(False)

# KNN Confusion Matrix
cm_knn = confusion_matrix(y_test, y_pred_knn)
cmd_knn = ConfusionMatrixDisplay(confusion_matrix=cm_knn, display_labels=[f'Cluster {i}' for i in range(3)])
cmd_knn.plot(ax=axes[1], cmap='Greens', values_format='d')
axes[1].set_title('KNN Confusion Matrix (Predicting Clusters)')
axes[1].grid(False)

plt.tight_layout()
plt.show()

